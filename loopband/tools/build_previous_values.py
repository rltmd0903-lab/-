def sheet(name, head, rows, fills, widths, notes=(), warns=None):
    """head: 열 이름, fills: 열마다 V1/V2/NEW/None, warns: {(행, 열): 설명} (데이터 행 0부터)."""
    ws = wb.create_sheet(name)
    for j, h in enumerate(head, 1):
        c = ws.cell(1, j, h)
        c.font, c.fill, c.alignment, c.border = Font(name=FONT, size=10, bold=True, color="FFFFFF"), HDR, CENTER, BOX
    for i, row in enumerate(rows):
        for j, v in enumerate(row):
            c = ws.cell(i + 2, j + 1, v)
            c.font, c.alignment, c.border = Font(name=FONT, size=10), CENTER, BOX
            if fills[j] is not None:
                c.fill = fills[j]
            if warns and (i, j) in warns:
                c.fill = WARN
                c.comment = Comment(warns[(i, j)], "검토")
    for j, w in enumerate(widths, 1):
        ws.column_dimensions[L(j)].width = w
    ws.row_dimensions[1].height = 32
    r = len(rows) + 3
    for n in notes:
        c = ws.cell(r, 1, n)
        c.font = Font(name=FONT, size=9, color="595959")
        r += 1
    ws.freeze_panes = "B2"
    return ws


