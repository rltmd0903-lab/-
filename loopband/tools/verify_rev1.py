print('\n--- 통제집단 15명→14명(1명 제외)으로 1차→2차 변환이 가능한가 ---')
def drop1(m15,s15,m14,s14):
    x=15*m15-14*m14
    ss15=s15**2*14
    ss14=ss15-(x-m15)**2*15/14
    return x, (math.sqrt(ss14/13) if ss14>0 else float('nan'))
